const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('desktopAPI', {
  setAlwaysOnTop: (enabled) => ipcRenderer.invoke('window:set-always-on-top', enabled),
  setOpacity: (value) => ipcRenderer.invoke('window:set-opacity', value),
  isAlwaysOnTop: () => ipcRenderer.invoke('window:is-always-on-top'),
  listExternalWindows: () => ipcRenderer.invoke('external-windows:list'),
  previewExternalWindow: (handle) => ipcRenderer.invoke('external-windows:preview', handle),
  toggleExternalWindowPin: (handle, enabled) => ipcRenderer.invoke('external-windows:toggle-pin', { handle, enabled }),
  minimize: () => ipcRenderer.send('window:minimize'),
  close: () => ipcRenderer.send('window:close'),
  toggleWidget: () => ipcRenderer.invoke('widget:toggle'),
  sendWidgetState: (state) => ipcRenderer.send('widget:state', state),
  sendWidgetCommand: (command) => ipcRenderer.send('widget:command', command),
  closeWidget: () => ipcRenderer.send('widget:close'),
  widgetReady: () => ipcRenderer.send('widget:ready'),
  onWidgetState: (callback) => ipcRenderer.on('widget:state', (_event, state) => callback(state)),
  onWidgetCommand: (callback) => ipcRenderer.on('widget:command', (_event, command) => callback(command)),
  onWidgetVisibility: (callback) => ipcRenderer.on('widget:visibility', (_event, visible) => callback(visible)),
  onWidgetRequestState: (callback) => ipcRenderer.on('widget:request-state', (_event) => callback()),
  openNoteWindow: (note) => ipcRenderer.invoke('notes:open', note),
  updateNoteWindow: (note) => ipcRenderer.send('notes:update', note),
  closeNoteWindow: (id) => ipcRenderer.send('notes:close', id),
  onNotesUpdated: (callback) => ipcRenderer.on('notes:updated', (_event, note) => callback(note)),
  onNoteState: (callback) => ipcRenderer.on('note:state', (_event, note) => callback(note)),
  getClipboard: () => ipcRenderer.invoke('clipboard:get'),
  setClipboardEnabled: (enabled) => ipcRenderer.invoke('clipboard:set-enabled', enabled),
  copyClipboard: (text) => ipcRenderer.invoke('clipboard:copy', text),
  clearClipboard: () => ipcRenderer.invoke('clipboard:clear'),
  pinClipboard: (id) => ipcRenderer.invoke('clipboard:pin', id),
  onClipboardUpdated: (callback) => ipcRenderer.on('clipboard:updated', (_event, history) => callback(history)),
  getShortcuts: () => ipcRenderer.invoke('shortcuts:get'),
  saveShortcuts: (shortcuts) => ipcRenderer.invoke('shortcuts:save', shortcuts),
  captureScreen: () => ipcRenderer.invoke('system:capture-screen'),
  generateQr: (text) => ipcRenderer.invoke('qr:generate', text),
  openSpeechFile: () => ipcRenderer.invoke('tts:open-file'),
  notify: (title, body) => ipcRenderer.invoke('system:notify', { title, body }),
  scheduleReminder: (reminder) => ipcRenderer.invoke('reminder:schedule', reminder),
  cancelReminder: (id) => ipcRenderer.invoke('reminder:cancel', id),
  onReminderFired: (callback) => ipcRenderer.on('reminder:fired', (_event, id) => callback(id)),
  onShortcutTriggered: (callback) => ipcRenderer.on('shortcut:triggered', (_event, name) => callback(name))
});
